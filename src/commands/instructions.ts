// orq instructions — the /issue playbook (skills/issue/SKILL.md, one source) in the conductor's own format:
//   claude   <workspace>/.claude/skills/issue/SKILL.md   (Claude Code loads it as the /issue skill)
//   agents   <workspace>/AGENTS.md                        (Codex, OpenCode and others that read AGENTS.md)
// AGENTS.md may hold the user's own text: orq only replaces its block between the orq:issue markers.
//   orq instructions claude|agents [-w <workspace>] [--print]
import { existsSync, readFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { writeAtomic } from "../fsutil.js";
import { m } from "../i18n.js";

export const USAGE = "orq instructions claude|agents [-w <workspace>] [--print]   write the /issue playbook for the conductor";

const SRC = fileURLToPath(new URL("../../skills/issue/SKILL.md", import.meta.url));
const BEGIN = "<!-- orq:issue begin (generated by `orq instructions agents`; edits inside are overwritten) -->";
const END = "<!-- orq:issue end -->";

/** The playbook for harnesses without skills: no frontmatter, a trigger line, and how to wait without background tasks. */
export function agentsBlock(skill: string): string {
  const body = skill.replace(/^---\r?\n[\s\S]*?\r?\n---\r?\n/, "").trim();
  return `${BEGIN}
When the user says "/issue <ID>", "take issue X" or "run ABC-123", follow this playbook.
If your harness cannot run a command in the background, wait for children with \`orq wait\` in the foreground
(\`orq wait --any <prefix>...\`): it is the one allowed blocking wait.

${body}
${END}
`;
}

/** Put the block into an existing AGENTS.md text: replace ours, or append it. */
export function mergeBlock(cur: string, block: string): string {
  const a = cur.indexOf(BEGIN), b = cur.indexOf(END);
  if (a >= 0 && b > a) return cur.slice(0, a) + block.trimEnd() + cur.slice(b + END.length);
  return cur ? `${cur.trimEnd()}\n\n${block}` : block;
}

export async function instructions(argv: string[]): Promise<number> {
  let ws = process.cwd(), print = false, fmt: string | undefined;
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "-w") ws = resolve(argv[++i]); else if (argv[i] === "--print") print = true;
    else if (argv[i] === "claude" || argv[i] === "agents") fmt = argv[i]; else { console.error(USAGE); return 2; }
  }
  if (!fmt) { console.error(USAGE); return 2; }
  if (!existsSync(SRC)) { console.error(m(`playbook not found: ${SRC}`, `playbook não encontrado: ${SRC}`)); return 2; }
  const skill = readFileSync(SRC, "utf8");
  const file = fmt === "claude" ? join(ws, ".claude", "skills", "issue", "SKILL.md") : join(ws, "AGENTS.md");
  const text = fmt === "claude" ? skill : mergeBlock(existsSync(file) ? readFileSync(file, "utf8") : "", agentsBlock(skill));
  if (print) { process.stdout.write(text); return 0; }
  writeAtomic(file, text);
  console.log(m(`wrote ${file}`, `escrito ${file}`));
  return 0;
}

