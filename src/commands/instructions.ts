// orq instructions — the /issue playbook (skills/issue/SKILL.md, one source) in the conductor's own format:
//   claude   <workspace>/.claude/skills/issue/SKILL.md   (Claude Code loads it as the /issue skill)
//   agents   <workspace>/AGENTS.md                        (Codex, OpenCode and others that read AGENTS.md)
// AGENTS.md may hold the user's own text: orq only replaces its block between the orq:issue markers.
//   orq instructions claude|agents [-w <workspace>] [--conductor <agent>] [--print]
//   orq instructions strategy [-w <workspace>] [--conductor <agent>] [--json]   which wait/resume strategy applies (#119)
import { existsSync, readFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { writeAtomic } from "../fsutil.js";
import { getPath, loadConfig, type Obj } from "../config.js";
import { capabilities, loopTimeout, strategy, strategyText } from "../harness.js";
import { m } from "../i18n.js";

export const USAGE = `orq instructions claude|agents [-w <workspace>] [--conductor <agent>] [--print]   write the /issue playbook for the conductor
orq instructions strategy [-w <workspace>] [--conductor <agent>] [--json]   show the conductor's wait/resume strategy`;

const SRC = fileURLToPath(new URL("../../skills/issue/SKILL.md", import.meta.url));
const BEGIN = "<!-- orq:issue begin (generated by `orq instructions agents`; edits inside are overwritten) -->";
const END = "<!-- orq:issue end -->";

/** The playbook for harnesses without skills: no frontmatter, a trigger line, and the conductor's waiting strategy. */
export function agentsBlock(skill: string, waiting = strategyText("unknown", capabilities("unknown"))): string {
  const body = skill.replace(/^---\r?\n[\s\S]*?\r?\n---\r?\n/, "").trim();
  return `${BEGIN}
When the user says "/issue <ID>", "take issue X" or "run ABC-123", follow this playbook.
Read \`ORQ.md\` for the workspace map and orchestration settings (legacy workspaces: \`CLAUDE.md\`).

${waiting}

${body}
${END}
`;
}

/** Put the block into an existing AGENTS.md text: replace ours, or append it. */
export function mergeBlock(cur: string, block: string): string {
  const a = cur.indexOf(BEGIN), b = cur.indexOf(END);
  if (a >= 0 && b > a) return cur.slice(0, a) + block.trimEnd() + cur.slice(b + END.length);
  return cur ? `${cur.trimEnd()}\n\n${block}` : block;
}

/** Conductor agent: --conductor, else roles.conductor.agent, else claude. */
function conductorOf(cfg: Obj, flag?: string): string {
  return flag || String(getPath(cfg, "roles.conductor.agent") ?? "claude");
}

/** AGENTS.md is read by non-Claude harnesses: a Claude conductor's wake-up must not leak into it unless asked for. */
function agentsWaiting(agent: string, caps: ReturnType<typeof capabilities>, cfg: Obj, flag?: string): string {
  if (agent === "claude" && !flag) return strategyText("AGENTS.md harness", capabilities("unknown", cfg, process.env));
  return strategyText(agent, caps);
}

export async function instructions(argv: string[]): Promise<number> {
  let ws = process.cwd(), print = false, json = false, fmt: string | undefined, who: string | undefined;
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "-w") ws = resolve(argv[++i]); else if (a === "--print") print = true; else if (a === "--json") json = true;
    else if (a === "--conductor" && argv[i + 1]) who = argv[++i];
    else if (a === "claude" || a === "agents" || a === "strategy") fmt = a; else { console.error(USAGE); return 2; }
  }
  if (!fmt) { console.error(USAGE); return 2; }
  let cfg: Obj = {};
  try { cfg = loadConfig(ws).cfg; } catch { /* no config: built-in defaults */ }
  const agent = conductorOf(cfg, who), caps = capabilities(agent, cfg, process.env), s = strategy(caps);
  if (fmt === "strategy") {
    const fallback = s === "background-task" ? "foreground-loop" : "none";
    if (json) { console.log(JSON.stringify({ conductor: agent, strategy: s, fallback, waitTimeout: loopTimeout(caps), capabilities: caps })); return 0; }
    console.log(`conductor ${agent}: ${s}`);
    console.log(`  background=${caps.background} resume_on_completion=${caps.resumeOnCompletion} foreground_wait=${caps.foregroundWait} prompt_delivery=${caps.promptDelivery} foreground_timeout=${caps.foregroundTimeout}s`);
    console.log(s === "background-task"
      ? m("  ends its turn after dispatch; orq wait in the background wakes it (fallback: foreground loop)",
        "  encerra o turno após o dispatch; o orq wait em background o acorda (fallback: loop em foreground)")
      : s === "manual"
      ? m("  cannot continue by itself: reports pending prefixes and waits for the user's message",
        "  não continua sozinho: informa os prefixos pendentes e espera a mensagem do usuário")
      : m(`  stays active: orq wait --any --timeout ${loopTimeout(caps)} in a loop; it does NOT resume by itself after ending a turn`,
        `  fica ativo: orq wait --any --timeout ${loopTimeout(caps)} em loop; NÃO retoma sozinho depois de encerrar o turno`));
    console.log(m(`  override: agents.${agent}.conductor.capabilities`, `  ajuste: agents.${agent}.conductor.capabilities`));
    return 0;
  }
  if (!existsSync(SRC)) { console.error(m(`playbook not found: ${SRC}`, `playbook não encontrado: ${SRC}`)); return 2; }
  const skill = readFileSync(SRC, "utf8");
  const file = fmt === "claude" ? join(ws, ".claude", "skills", "issue", "SKILL.md") : join(ws, "AGENTS.md");
  const text = fmt === "claude" ? skill : mergeBlock(existsSync(file) ? readFileSync(file, "utf8") : "", agentsBlock(skill, agentsWaiting(agent, caps, cfg, who)));
  if (print) { process.stdout.write(text); return 0; }
  writeAtomic(file, text);
  console.log(m(`wrote ${file}`, `escrito ${file}`));
  return 0;
}

